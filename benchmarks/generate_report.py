"""
benchmarks/generate_report.py - Regenerate benchmarks/performance_results.json.

Runs simplify_mesh() across a range of triangle targets on the same source
mesh so the numbers in the README's benchmark table are reproducible rather
than hand-typed.

Usage:
    python benchmarks/generate_report.py
"""

import json
from pathlib import Path

import open3d as o3d

from optimizer.core import clean_mesh, load_mesh, save_mesh, simplify_mesh
from optimizer.metrics import build_report

BENCH_DIR = Path(__file__).parent
SOURCE_PATH = BENCH_DIR / "_source.stl"
OUTPUT_DIR = BENCH_DIR / "_output"
TARGETS = [20_000, 10_000, 5_000, 2_000, 1_000, 500]


def _make_source_mesh() -> None:
    """A ~390k-triangle subdivided sphere, large enough to be a meaningful
    decimation benchmark, generated on the fly so no binary asset is
    committed to the repo."""
    sphere = o3d.geometry.TriangleMesh.create_sphere(radius=0.5)
    for _ in range(4):
        sphere = sphere.subdivide_midpoint(1)
    sphere.compute_triangle_normals()
    o3d.io.write_triangle_mesh(str(SOURCE_PATH), sphere)


def main() -> None:
    _make_source_mesh()
    OUTPUT_DIR.mkdir(exist_ok=True)

    mesh = clean_mesh(load_mesh(str(SOURCE_PATH)))
    results = []

    for target in TARGETS:
        out_path = OUTPUT_DIR / f"bench_{target}.stl"
        result, elapsed = simplify_mesh(mesh, target)
        save_mesh(result, str(out_path))
        report = build_report(
            str(SOURCE_PATH), str(out_path), mesh, result, elapsed, compute_hausdorff=True
        )
        # Store paths relative to the repo root so the committed report
        # doesn't bake in the local filesystem layout of whoever generated it.
        report["input_file"] = str(SOURCE_PATH.relative_to(BENCH_DIR.parent))
        report["output_file"] = str(out_path.relative_to(BENCH_DIR.parent))
        results.append(report)
        print(f"  {target:>7,} -> {len(result.triangles):>7,} triangles  ({elapsed:.3f}s)")

    report_path = BENCH_DIR / "performance_results.json"
    with open(report_path, "w") as f:
        json.dump(
            {
                "_note": "Generated by benchmarks/generate_report.py. Re-run it to reproduce.",
                "_source": "Synthetic subdivided sphere, ~390k triangles.",
                "results": results,
            },
            f,
            indent=2,
        )
        f.write("\n")
    print(f"\nSaved -> {report_path}")


if __name__ == "__main__":
    main()
